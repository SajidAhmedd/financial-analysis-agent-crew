def sanitize_text(text: str) -> str:
    """
    Remove or replace characters that can't be encoded in latin-1.

    WHY: fpdf2 uses latin-1 encoding which doesn't support
    special Unicode characters like curly quotes, em-dashes, etc.
    """
    if not text:
        return ""

    # Common replacements
    replacements = {
        '\u2019': "'",   # Right single quote
        '\u2018': "'",   # Left single quote
        '\u201c': '"',   # Left double quote
        '\u201d': '"',   # Right double quote
        '\u2013': '-',   # En-dash
        '\u2014': '--',  # Em-dash
        '\u2026': '...', # Ellipsis
        '\u00a0': ' ',   # Non-breaking space
        '\u200b': '',    # Zero-width space
    }

    for char, replacement in replacements.items():
        text = text.replace(char, replacement)

    # Remove any remaining non-latin-1 characters
    text = text.encode('latin-1', errors='ignore').decode('latin-1')

    return text

# CUSTOM PDF CLASS

class FinancialReportPDF(FPDF):
    """
    Custom PDF class for financial reports.

    WHY A CUSTOM CLASS:
    - Adds automatic headers and footers
    - Provides consistent styling
    - Encapsulates report-specific logic

    INHERITS FROM:
    - FPDF: The base class from fpdf2 library
    """

    def __init__(self, ticker: str, company_name: str):
        super().__init__()
        self.ticker = ticker.upper()
        self.company_name = company_name
        self.report_date = datetime.now().strftime("%B %d, %Y")

        # Set up document
        self.set_auto_page_break(auto=True, margin=15)
        self.set_margins(15, 15, 15)

    def header(self):
        """
        Automatic header on every page.
        Called automatically by FPDF when a new page is added.
        """
        # Company name and ticker
        self.set_font('Helvetica', 'B', 16)
        self.set_text_color(41, 98, 255)  # Blue
        self.cell(0, 10, f"{self.company_name} ({self.ticker})", align='L')

        # Report title on right
        self.set_font('Helvetica', '', 10)
        self.set_text_color(100, 100, 100)  # Gray
        self.cell(0, 10, "Financial Analysis Report", align='R', ln=True)

        # Horizontal line
        self.set_draw_color(200, 200, 200)
        self.line(15, 25, 195, 25)
        self.ln(10)

    def footer(self):
        """
        Automatic footer on every page.
        Called automatically by FPDF.
        """
        self.set_y(-15)  # Position 15mm from bottom
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)

        # Page number
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}}", align='C')

    def add_title_page(self):
        """Create the report title page."""
        self.add_page()

        # Large title
        self.ln(40)
        self.set_font('Helvetica', 'B', 32)
        self.set_text_color(41, 98, 255)
        self.cell(0, 20, "Financial Analysis", align='C', ln=True)
        self.cell(0, 20, "Report", align='C', ln=True)

        # Company name
        self.ln(20)
        self.set_font('Helvetica', 'B', 24)
        self.set_text_color(0, 0, 0)
        self.cell(0, 15, self.company_name, align='C', ln=True)

        # Ticker
        self.set_font('Helvetica', '', 18)
        self.set_text_color(100, 100, 100)
        self.cell(0, 10, f"({self.ticker})", align='C', ln=True)

        # Date
        self.ln(30)
        self.set_font('Helvetica', '', 14)
        self.cell(0, 10, f"Report Generated: {self.report_date}", align='C', ln=True)

        # Branding
        self.ln(40)
        self.set_font('Helvetica', 'I', 10)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, "Generated by Financial Analysis Agent Crew", align='C', ln=True)
        self.cell(0, 10, "Powered by AI Multi-Agent System", align='C', ln=True)

    def add_section_header(self, title: str):
        """Add a styled section header."""
        self.ln(5)
        self.set_font('Helvetica', 'B', 14)
        self.set_text_color(41, 98, 255)
        self.cell(0, 10, title, ln=True)

        # Underline
        self.set_draw_color(41, 98, 255)
        y = self.get_y()
        self.line(15, y, 100, y)
        self.ln(5)

        # Reset text color
        self.set_text_color(0, 0, 0)

    def add_paragraph(self, text: str):
        """Add a paragraph of text."""
        self.set_font('Helvetica', '', 11)
        self.set_text_color(50, 50, 50)
        self.multi_cell(0, 6, sanitize_text(text))
        self.ln(3)

    def add_key_value(self, key: str, value: str):
        """Add a key-value pair (like 'P/E Ratio: 25.5')."""
        self.set_font('Helvetica', 'B', 10)
        self.set_text_color(80, 80, 80)
        self.cell(60, 7, f"{sanitize_text(key)}:", align='L')

        self.set_font('Helvetica', '', 10)
        self.set_text_color(0, 0, 0)
        self.cell(0, 7, sanitize_text(str(value)), align='L', ln=True)

    def add_metrics_table(self, metrics: Dict[str, Any], title: str = "Key Metrics"):
        """
        Add a formatted table of metrics.

        Creates a nice two-column table for displaying KPIs.
        """
        self.add_section_header(title)

        # Table styling
        self.set_fill_color(245, 245, 245)  # Light gray background
        self.set_draw_color(200, 200, 200)  # Border color

        row_count = 0
        for key, value in metrics.items():
            if value == 'N/A' or value is None:
                continue

            # Alternate row colors
            fill = row_count % 2 == 0

            # Format the key nicely
            display_key = key.replace('_', ' ').title()

            # Format value
            if isinstance(value, float):
                if abs(value) < 1 and value != 0:
                    display_value = f"{value:.4f}"
                else:
                    display_value = f"{value:.2f}"
            else:
                display_value = str(value)

            # Draw cells
            self.set_font('Helvetica', 'B', 10)
            self.cell(80, 8, display_key, border=1, fill=fill)
            self.set_font('Helvetica', '', 10)
            self.cell(100, 8, display_value, border=1, fill=fill, ln=True)

            row_count += 1

        self.ln(5)

    def add_image_full_width(self, image_path: str, caption: str = ""):
        """Add an image that spans the full page width."""
        if not os.path.exists(image_path):
            self.add_paragraph(f"[Image not found: {image_path}]")
            return

        # Calculate width to fit page (with margins)
        page_width = 180  # 210mm page - 15mm margins each side

        self.image(image_path, x=15, w=page_width)

        if caption:
            self.set_font('Helvetica', 'I', 9)
            self.set_text_color(100, 100, 100)
            self.cell(0, 5, caption, align='C', ln=True)
            self.set_text_color(0, 0, 0)

        self.ln(5)

    def add_news_item(self, index: int, title: str, source: str, sentiment: str, snippet: str = ""):
        """Add a formatted news item."""
        # Sentiment icon
        sentiment_colors = {
            'positive': (38, 166, 154),   # Green
            'negative': (239, 83, 80),    # Red
            'neutral': (120, 144, 156),   # Gray
        }
        color = sentiment_colors.get(sentiment, (120, 144, 156))

        # Title with number
        self.set_font('Helvetica', 'B', 10)
        self.set_text_color(0, 0, 0)
        self.cell(8, 6, f"{index}.")

        # Sentiment indicator
        self.set_text_color(*color)
        self.cell(5, 6, "[" + sentiment[0].upper() + "]")

        # Title - SANITIZED
        self.set_text_color(0, 0, 0)
        clean_title = sanitize_text(title[:80] + ("..." if len(title) > 80 else ""))
        self.multi_cell(0, 6, clean_title)

        # Source
        self.set_font('Helvetica', 'I', 9)
        self.set_text_color(100, 100, 100)
        self.cell(0, 5, f"Source: {sanitize_text(source)}", ln=True)

        # Snippet - SANITIZED
        if snippet:
            self.set_font('Helvetica', '', 9)
            truncated = snippet[:150] + "..." if len(snippet) > 150 else snippet
            self.multi_cell(0, 5, sanitize_text(truncated))

        self.ln(3)

# REPORT GENERATION FUNCTIONS

def generate_report(
    ticker: str,
    company_info: Dict[str, Any],
    key_metrics: Dict[str, Any],
    price_stats: Dict[str, Any],
    news_data: Dict[str, Any],
    chart_paths: Dict[str, str],
    ai_analysis: str = "",
    recommendations: str = ""
) -> str:
    """
    Generate a complete financial analysis PDF report.

    THIS IS THE MAIN FUNCTION for report generation.
    The Report Writer Agent will call this with all the data.

    PARAMETERS:
    - ticker: Stock symbol
    - company_info: From finance_tools.get_company_info()
    - key_metrics: From finance_tools.get_key_metrics()
    - price_stats: From finance_tools.get_price_statistics()
    - news_data: From news_tools.search_stock_news()
    - chart_paths: From chart_tools.create_all_charts()
    - ai_analysis: LLM-generated analysis text
    - recommendations: LLM-generated recommendations

    RETURNS:
    - Path to the generated PDF file
    """
    company_name = company_info.get('name', ticker)

    # Create PDF
    pdf = FinancialReportPDF(ticker, company_name)
    pdf.alias_nb_pages()  # Enable total page count in footer

    # === TITLE PAGE ===
    pdf.add_title_page()

    # === EXECUTIVE SUMMARY PAGE ===
    pdf.add_page()
    pdf.add_section_header("Executive Summary")

    # Company overview - show full description (PDF will handle pagination)
    description = company_info.get('description', 'No description available.')
    pdf.add_paragraph(description)

    # Quick stats
    pdf.ln(5)
    pdf.add_key_value("Sector", company_info.get('sector', 'N/A'))
    pdf.add_key_value("Industry", company_info.get('industry', 'N/A'))
    pdf.add_key_value("Country", company_info.get('country', 'N/A'))
    pdf.add_key_value("Employees", str(company_info.get('employees', 'N/A')))

    # === AI ANALYSIS (if provided) ===
    if ai_analysis:
        pdf.ln(5)
        pdf.add_section_header("AI Analysis")
        pdf.add_paragraph(ai_analysis)

    # === KEY METRICS PAGE ===
    pdf.add_page()

    # Price metrics
    price_metrics = {
        "Current Price": f"${key_metrics.get('current_price', 'N/A')}",
        "Previous Close": f"${key_metrics.get('previous_close', 'N/A')}",
        "52-Week High": f"${key_metrics.get('fifty_two_week_high', 'N/A')}",
        "52-Week Low": f"${key_metrics.get('fifty_two_week_low', 'N/A')}",
        "Market Cap": key_metrics.get('market_cap_formatted', 'N/A'),
    }
    pdf.add_metrics_table(price_metrics, "Price Information")

    # Valuation metrics
    valuation_metrics = {
        "P/E Ratio": key_metrics.get('pe_ratio', 'N/A'),
        "Forward P/E": key_metrics.get('forward_pe', 'N/A'),
        "PEG Ratio": key_metrics.get('peg_ratio', 'N/A'),
        "Price to Book": key_metrics.get('price_to_book', 'N/A'),
    }
    pdf.add_metrics_table(valuation_metrics, "Valuation Metrics")

    # Performance metrics
    performance_metrics = {
        "Period Return": f"{price_stats.get('period_return_pct', 'N/A')}%",
        "Daily Volatility": f"{price_stats.get('daily_volatility_pct', 'N/A')}%",
        "Annualized Volatility": f"{price_stats.get('annualized_volatility_pct', 'N/A')}%",
        "Period High": f"${price_stats.get('period_high', 'N/A')}",
        "Period Low": f"${price_stats.get('period_low', 'N/A')}",
    }
    pdf.add_metrics_table(performance_metrics, "Performance Statistics")

    # === CHARTS PAGE ===
    pdf.add_page()
    pdf.add_section_header("Price Analysis")

    # Price chart
    if chart_paths.get('price'):
        pdf.add_image_full_width(
            chart_paths['price'],
            "Stock price history with moving averages and volume"
        )

    # KPI chart (new page if needed)
    if chart_paths.get('kpi'):
        pdf.add_page()
        pdf.add_section_header("Financial Metrics Visualization")
        pdf.add_image_full_width(
            chart_paths['kpi'],
            "Key financial metrics comparison"
        )

    # === SENTIMENT ANALYSIS PAGE ===
    pdf.add_page()
    pdf.add_section_header("Market Sentiment Analysis")

    # Sentiment summary
    overall_sentiment = news_data.get('overall_sentiment', {})
    sentiment_label = overall_sentiment.get('label', 'unknown').upper()
    sentiment_score = overall_sentiment.get('score', 0)

    pdf.add_paragraph(
        f"Based on analysis of {news_data.get('total_articles', 0)} recent news articles, "
        f"the overall market sentiment for {ticker} is {sentiment_label} "
        f"(score: {sentiment_score:.2f} on a scale of -1 to +1)."
    )

    # Sentiment breakdown
    pdf.ln(3)
    pdf.add_key_value("Positive Articles", str(overall_sentiment.get('positive_articles', 0)))
    pdf.add_key_value("Neutral Articles", str(overall_sentiment.get('neutral_articles', 0)))
    pdf.add_key_value("Negative Articles", str(overall_sentiment.get('negative_articles', 0)))

    # Sentiment chart
    if chart_paths.get('sentiment'):
        pdf.ln(5)
        pdf.add_image_full_width(
            chart_paths['sentiment'],
            "Sentiment distribution and score"
        )

    # Recent news
    pdf.add_section_header("Recent News Headlines")
    articles = news_data.get('articles', [])[:5]  # Top 5 articles

    for i, article in enumerate(articles, 1):
        pdf.add_news_item(
            index=i,
            title=article.get('title', 'No title'),
            source=article.get('source', 'Unknown'),
            sentiment=article.get('sentiment', {}).get('label', 'neutral'),
            snippet=article.get('snippet', '')
        )

    # === RECOMMENDATIONS PAGE (if provided) ===
    if recommendations:
        pdf.add_page()
        pdf.add_section_header("Recommendations")
        pdf.add_paragraph(recommendations)

    # === DISCLAIMER PAGE ===
    pdf.add_page()
    pdf.add_section_header("Disclaimer")
    pdf.set_font('Helvetica', 'I', 9)
    pdf.multi_cell(0, 5,
        "This report is generated by an AI-powered financial analysis system for "
        "informational purposes only. It does not constitute financial advice, "
        "investment recommendations, or an offer to buy or sell securities.\n\n"
        "The information contained herein is based on publicly available data and "
        "automated analysis. While efforts have been made to ensure accuracy, no "
        "guarantee is made regarding the completeness or reliability of this information.\n\n"
        "Past performance is not indicative of future results. Investing involves risk, "
        "including the possible loss of principal. Always consult with a qualified "
        "financial advisor before making investment decisions.\n\n"
        f"Report generated on {datetime.now().strftime('%Y-%m-%d at %H:%M:%S')}"
    )

    # === SAVE PDF ===
    output_dir = os.path.join(project_root, OUTPUT_DIR)
    os.makedirs(output_dir, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{ticker}_Financial_Report_{timestamp}.pdf"
    filepath = os.path.join(output_dir, filename)

    pdf.output(filepath)
    print(f"PDF Report saved: {filepath}")

    return filepath

